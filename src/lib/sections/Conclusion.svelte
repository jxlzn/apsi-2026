      <p class="lead reveal">Publishing an annual sustainability report is now standard practice for Asia Pacific’s largest listed companies. The inaugural Asia Pacific Sustainability Index (APSI) reflects this, with the headline regional score of 78.9 out of 110 and base score of 75.5 out of 100.</p>
      <p class="reveal">What sits behind those numbers however is a divide between disclosure and execution. While 93.8 per cent of companies adopt global normative frameworks and over 80 per cent disclose climate risks, the market remains stalled at qualitative declarations. Only 28 per cent quantify climate scenarios, fewer than one in five report comprehensive Scope 3 value-chain categories, and just 41 per cent disclose qualified sustainability capabilities in the boardroom.</p>
      <p class="reveal">With jurisdictions across the region rapidly converging on mandatory ISSB standards and statutory external assurance, soft narrative disclosures are no longer enough. For corporate leadership in Asia-Pacific, future competitiveness hinges on treating sustainability as a core driver of operational resilience and long-term value creation.</p>
